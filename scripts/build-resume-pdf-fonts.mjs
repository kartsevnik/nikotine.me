/**
 * Builds js/vendor/resume-pdf-vfs.js from Manrope + EB Garamond TTF files.
 *
 * Prerequisites (one-time):
 *   1. Download variable fonts into scripts/fonts/ (see download step below)
 *   2. Instantiate static weights with fonttools (Python):
 *        pip install fonttools
 *        python scripts/instantiate-resume-fonts.py
 *   3. node scripts/build-resume-pdf-fonts.mjs
 *
 * Or run: npm run build:resume-pdf-fonts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const fontsDir = path.join(__dirname, "fonts");
const outFile = path.join(root, "js", "vendor", "resume-pdf-vfs.js");

const REQUIRED = [
  "Manrope-Regular.ttf",
  "EBGaramond-Medium.ttf",
  "EBGaramond-SemiBold.ttf",
];

/** Still instantiate SemiBold locally for experiments; not embedded in VFS. */
const OPTIONAL_STATIC = ["Manrope-SemiBold.ttf"];

const VARIABLE = [
  {
    file: "Manrope-Variable.ttf",
    url: "https://raw.githubusercontent.com/google/fonts/main/ofl/manrope/Manrope%5Bwght%5D.ttf",
  },
  {
    file: "EBGaramond-Variable.ttf",
    url: "https://raw.githubusercontent.com/google/fonts/main/ofl/ebgaramond/EBGaramond%5Bwght%5D.ttf",
  },
];

async function download(url, dest) {
  const res = await fetch(url, { redirect: "follow" });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.length < 1000) throw new Error(`File too small from ${url}`);
  fs.writeFileSync(dest, buf);
  return buf.length;
}

async function ensureVariableFonts() {
  fs.mkdirSync(fontsDir, { recursive: true });
  for (const item of VARIABLE) {
    const dest = path.join(fontsDir, item.file);
    if (fs.existsSync(dest) && fs.statSync(dest).size > 1000) {
      console.log(`OK  ${item.file} (cached)`);
      continue;
    }
    console.log(`GET ${item.url}`);
    const size = await download(item.url, dest);
    console.log(`OK  ${item.file} (${size} bytes)`);
  }
}

function ensureStaticFonts() {
  const needed = REQUIRED.concat(OPTIONAL_STATIC);
  const missing = needed.filter((name) => {
    const p = path.join(fontsDir, name);
    return !(fs.existsSync(p) && fs.statSync(p).size > 1000);
  });
  if (!missing.length) {
    console.log("OK  static TTF weights present");
    return;
  }

  console.log("Instantiating static weights via fonttools…");
  const py = path.join(__dirname, "instantiate-resume-fonts.py");
  const result = spawnSync("python", [py], { stdio: "inherit", cwd: root });
  if (result.status !== 0) {
    throw new Error(
      "fonttools instantiation failed. Install with: pip install fonttools"
    );
  }
}

function buildVfs() {
  const vfs = {};
  for (const name of REQUIRED) {
    const filePath = path.join(fontsDir, name);
    if (!fs.existsSync(filePath)) {
      throw new Error(`Missing font: ${filePath}`);
    }
    vfs[name] = fs.readFileSync(filePath).toString("base64");
  }

  const fonts = {
    Manrope: {
      // Same file for all variants: paired Manrope weights from variable-font
      // instantiation hang pdfmake when mixed. Hierarchy uses EBGaramond instead.
      normal: "Manrope-Regular.ttf",
      bold: "Manrope-Regular.ttf",
      italics: "Manrope-Regular.ttf",
      bolditalics: "Manrope-Regular.ttf",
    },
    EBGaramond: {
      normal: "EBGaramond-Medium.ttf",
      bold: "EBGaramond-SemiBold.ttf",
      italics: "EBGaramond-Medium.ttf",
      bolditalics: "EBGaramond-SemiBold.ttf",
    },
  };

  const source = `/* Auto-generated by scripts/build-resume-pdf-fonts.mjs — do not edit by hand. */
(function (root) {
  "use strict";
  var vfs = ${JSON.stringify(vfs)};
  var fonts = ${JSON.stringify(fonts, null, 2)};
  root.resumePdfFonts = { vfs: vfs, fonts: fonts };
  if (typeof root.pdfMake !== "undefined") {
    root.pdfMake.vfs = Object.assign({}, root.pdfMake.vfs || {}, vfs);
    root.pdfMake.fonts = Object.assign({}, root.pdfMake.fonts || {}, fonts);
  }
})(typeof self !== "undefined" ? self : this);
`;

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, source, "utf8");
  console.log(
    `Wrote ${outFile} (${Math.round(fs.statSync(outFile).size / 1024)} KB)`
  );
}

async function main() {
  await ensureVariableFonts();
  ensureStaticFonts();
  buildVfs();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
